import { test, expect } from '@playwright/test'
test.skip(!!process.env.AUTH_E2E, 'Local food records')

test('catalog, household portions and confirmation update totals once and survive reload', async ({
  page,
}, testInfo) => {
  await page.goto('/#/nutrition')
  const panel = page.getByRole('region', { name: '热量评估', exact: true })
  await panel.getByLabel('食品分类', { exact: true }).selectOption('水果类')
  await expect(panel.locator('.food-card').first()).toContainText('水果类')
  await panel.getByLabel('食品分类', { exact: true }).selectOption('全部')
  await panel.getByLabel('搜索食品', { exact: true }).fill('馍')
  await expect(panel.locator('.food-card').first()).toContainText('白馒头')
  await expect(panel.locator('.food-card').first()).toContainText('2.48')
  await panel.getByLabel('搜索食品', { exact: true }).fill('不存在的食品zz')
  await expect(panel).toContainText('没有找到匹配食品')
  await panel.getByRole('button', { name: '添加一碗米饭（熟）', exact: true }).click()
  await panel.getByRole('button', { name: '添加一个白馒头（熟）', exact: true }).click()
  const rows = panel.locator('.combination-row')
  await rows.nth(0).getByLabel('食用数量').fill('0.5')
  await rows.nth(1).getByLabel('每个克重').fill('80')
  await expect(panel.locator('.combination-total > strong')).toHaveText('335.7 kcal')
  await expect(page.locator('.history-row')).toHaveCount(0)
  await rows.nth(1).getByLabel('食用数量').fill('-1')
  await expect(panel.getByRole('button', { name: '确认组合并计入今日' })).toBeDisabled()
  await rows.nth(1).getByLabel('食用数量').fill('1')
  await page.screenshot({ path: testInfo.outputPath('food-catalog-desktop.png'), fullPage: true })
  await panel.getByRole('button', { name: '确认组合并计入今日' }).dblclick()
  await expect(page.locator('.history-row')).toHaveCount(2)
  await expect(panel.locator('.calorie-stats > div').first()).toContainText('335.7')
  await page.reload()
  await expect(page.locator('.history-row')).toHaveCount(2)
  await expect(panel.locator('.calorie-stats > div').first()).toContainText('335.7')
  await page
    .locator('.history-row')
    .filter({ hasText: '白馒头' })
    .getByRole('button', { name: '撤销计入' })
    .click()
  await expect(panel.locator('.calorie-stats > div').first()).toContainText('137.3')
})

test('unit conversion, removing foods and mobile layout', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/#/nutrition')
  const panel = page.getByRole('region', { name: '热量评估', exact: true })
  await panel.getByRole('button', { name: '添加一碗水煮面条（熟，参考估算）', exact: true }).click()
  const row = panel.locator('.combination-row')
  await row.getByLabel('计量单位').selectOption('g')
  await expect(row.getByLabel('食用数量')).toHaveValue('250')
  await row.getByLabel('计量单位').selectOption('碗')
  await expect(row.getByLabel('食用数量')).toHaveValue('1')
  const combinationBox = await panel.locator('.food-combination').boundingBox()
  const directoryBox = await panel.locator('.food-directory').boundingBox()
  expect(combinationBox.y).toBeLessThan(directoryBox.y)
  await page.screenshot({ path: testInfo.outputPath('food-catalog-mobile.png'), fullPage: true })
  await row.getByRole('button', { name: '移除水煮面条（熟，参考估算）' }).click()
  await expect(row).toHaveCount(0)
  await expect(panel.getByRole('button', { name: '确认组合并计入今日' })).toBeDisabled()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(
    true,
  )
})
