import {test,expect} from '@playwright/test'
test.skip(!!process.env.AUTH_E2E,'Local plans')
test('custom plan preview cancel is read-only and saving preserves history',async({page})=>{
 await page.addInitScript(()=>localStorage.setItem('tm_logs_v2',JSON.stringify({'2025-12-29|1-am':[{id:'old',name:'历史卧推',weight:'10',sets:'1',reps:'8'}]})))
 await page.goto('/#/training')
 await page.getByRole('button',{name:'自定义当日计划'}).click()
 const dialog=page.getByRole('dialog')
 await dialog.getByLabel('自定义计划名称').fill('私人训练日')
 await dialog.getByLabel('动作名称',{exact:true}).first().fill('自定义深蹲')
 await dialog.getByRole('button',{name:'预览自定义计划'}).click()
 await page.keyboard.press('Escape')
 expect(await page.evaluate(()=>localStorage.getItem('tm_vue_plans'))).toBeNull()
 await page.getByRole('button',{name:'自定义当日计划'}).click()
 await dialog.getByLabel('自定义计划名称').fill('私人训练日')
 await dialog.getByLabel('动作名称',{exact:true}).first().fill('自定义深蹲')
 await dialog.getByRole('button',{name:'预览自定义计划'}).click()
 await dialog.getByRole('button',{name:'确认保存自定义计划'}).click()
 await expect(page.locator('.exercise-row').first()).toContainText('自定义深蹲')
 await page.reload()
 await expect(page.locator('.exercise-row').first()).toContainText('自定义深蹲')
 await page.getByRole('button',{name:'训练记录',exact:true}).click()
 await expect(page.locator('.history-row')).toContainText('历史卧推')
})
