import { test, expect } from '@playwright/test'
test.skip(!!process.env.AUTH_E2E, 'Local meal records')
test('edit a meal across dates, search, copy and undo adjust the correct totals', async ({
  page,
}) => {
  await page.goto('/#/nutrition')
  await page.getByRole('button', { name: '手动记录饮食', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('饮食名称', { exact: true }).fill('测试鸡胸饭')
  await dialog.getByLabel('每份蛋白质').fill('30')
  await dialog.getByRole('button', { name: '保存并计入蛋白' }).click()
  await expect(page.locator('.protein-ring strong')).toHaveText('30')
  await page.getByRole('button', { name: '编辑饮食' }).click()
  await dialog.getByLabel('饮食日期').fill('2025-12-31')
  await dialog.getByLabel('食用份数').fill('2')
  await dialog.getByRole('button', { name: '保存并计入蛋白' }).click()
  await expect(page.locator('.protein-ring strong')).toHaveText('0')
  await page.getByLabel('搜索饮食记录').fill('不匹配')
  await expect(page.locator('.history-row')).toHaveCount(0)
  await page.getByLabel('搜索饮食记录').fill('鸡胸')
  await page.getByRole('button', { name: '复制到今天' }).click()
  await dialog.getByRole('button', { name: '保存并计入蛋白' }).click()
  await expect(page.locator('.protein-ring strong')).toHaveText('60')
  await page.getByRole('button', { name: '保存常用餐食' }).first().click()
  const library = page.getByRole('region', { name: '个人食物库与营养趋势' })
  await library.getByRole('button', { name: '使用餐食模板' }).click()
  await dialog.getByRole('button', { name: '保存并计入蛋白' }).click()
  await expect(page.locator('.protein-ring strong')).toHaveText('90')
  await expect(library).toContainText('蛋白90g')
  await expect(page.locator('.history-row')).toHaveCount(3)
  await page.reload()
  await expect(page.locator('.protein-ring strong')).toHaveText('90')
})
