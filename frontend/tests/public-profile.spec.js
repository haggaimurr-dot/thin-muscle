import { test, expect } from '@playwright/test'
test.skip(!!process.env.AUTH_E2E, 'Demo profile')
test('public profile persists explicit sharing settings', async ({ page }) => {
  await page.goto('/#/community')
  await page.getByRole('button', { name: '我的公开资料', exact: true }).click()
  const section = page.getByRole('region', { name: '我的公开资料' })
  const original = await section.getByLabel('公开昵称').inputValue()
  await section.getByLabel('公开昵称').fill('Profile test')
  await section.getByLabel('个人简介').fill('Visible only when opted in')
  await section.getByLabel('公开我的简介').check()
  await section.getByRole('button', { name: '保存公开资料' }).click()
  await expect(section.getByRole('status')).toContainText('已保存')
  await page.reload()
  await page.getByRole('button', { name: '我的公开资料', exact: true }).click()
  await expect(section.getByLabel('公开我的简介')).toBeChecked()
  await expect(section.getByLabel('个人简介')).toHaveValue('Visible only when opted in')
  await section.getByLabel('公开昵称').fill(original)
  await section.getByLabel('个人简介').fill('')
  await section.getByLabel('公开我的简介').uncheck()
  await section.getByRole('button', { name: '保存公开资料' }).click()
})
