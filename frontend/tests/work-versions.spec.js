import { test, expect } from '@playwright/test'
test.skip(!!process.env.AUTH_E2E, 'Demo work lifecycle')
test('partial draft survives reload, publishes, edits and unlists with version history', async ({
  page,
}) => {
  await page.goto('/#/market')
  await page.getByRole('button', { name: '发布作品', exact: true }).click()
  let dialog = page.getByRole('dialog', { name: '发布你的训练作品' })
  const title = 'Lifecycle ' + Date.now()
  await dialog.getByLabel('作品名称', { exact: true }).fill(title)
  await dialog.getByRole('button', { name: '保存作品草稿' }).click()
  await expect(page.getByText('草稿已保存，尚未发布')).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: '我发布的作品', exact: true }).click()
  await page.getByRole('button', { name: '继续编辑草稿' }).first().click()
  await expect(dialog.getByLabel('作品名称', { exact: true })).toHaveValue(title)
  await dialog.getByRole('button', { name: '确认上架' }).click()
  await expect(dialog).not.toBeVisible()
  const work = page.locator('.history-row').filter({ hasText: title })
  await work.getByRole('button', { name: '编辑作品', exact: true }).click()
  await dialog.getByLabel('作品介绍', { exact: true }).fill('Updated description')
  await dialog.getByRole('button', { name: '确认上架' }).click()
  await expect(work).toContainText('版本 2')
  await work.getByRole('button', { name: '作品版本历史' }).click()
  const history = page.getByRole('dialog', { name: '作品版本历史' })
  await expect(history).toContainText('版本 1')
  await expect(history).toContainText('版本 2')
  await history.getByRole('button', { name: '关闭', exact: true }).click()
  await work.getByRole('button', { name: '下架作品' }).click()
  await expect(work).toContainText('已下架')
  await page.reload()
  await page.getByRole('button', { name: '我发布的作品', exact: true }).click()
  await expect(work.getByRole('button', { name: '重新上架' })).toBeVisible()
})
