import { test, expect } from '@playwright/test'
test.skip(!!process.env.AUTH_E2E, 'Local candidate correction')
test('unknown barcode, manual split, independent correction and confirmation', async ({ page }) => {
  await page.goto('/#/nutrition')
  const panel = page.getByRole('region', { name: '条码与多食物记录' })
  await panel.getByLabel('商品条码数字').fill('4006381333932')
  await panel.getByRole('button', { name: '查询个人条码食物' }).click()
  await expect(panel.getByRole('alert')).toContainText('校验位无效')
  await panel.getByLabel('商品条码数字').fill('4006381333931')
  await panel.getByRole('button', { name: '查询个人条码食物' }).click()
  await expect(panel.getByRole('alert')).toContainText('未连接公共条码数据库')
  await panel.getByRole('button', { name: '手动增加拆分食物' }).click()
  await panel.getByRole('button', { name: '手动增加拆分食物' }).click()
  await panel.getByLabel('拆分食物名称').nth(0).fill('Rice')
  await panel.getByLabel('拆分食物名称').nth(1).fill('Chicken')
  await panel.getByLabel('拆分蛋白', { exact: true }).nth(0).fill('5')
  await panel.getByLabel('拆分蛋白', { exact: true }).nth(1).fill('30')
  await expect(page.locator('.protein-ring strong')).toHaveText('0')
  await panel.getByRole('button', { name: '确认逐项计入' }).click()
  await expect(page.locator('.protein-ring strong')).toHaveText('35')
  await expect(panel.getByLabel('拆分食物名称')).toHaveCount(0)
  await page.reload()
  await expect(page.locator('.protein-ring strong')).toHaveText('35')
  await page
    .locator('.history-row')
    .filter({ hasText: 'Rice' })
    .getByRole('button', { name: '保存常用餐食' })
    .click()
  await panel.getByLabel('绑定个人餐食模板').selectOption({ label: 'Rice' })
  await panel.getByLabel('商品条码数字').fill('4006381333931')
  await panel.getByRole('button', { name: '保存条码绑定' }).click()
  await page.reload()
  await panel.getByLabel('商品条码数字').fill('4006381333931')
  await panel.getByRole('button', { name: '查询个人条码食物' }).click()
  await expect(page.getByRole('dialog')).toContainText('手动记录')
})
