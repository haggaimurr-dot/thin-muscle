import { test, expect } from '@playwright/test'

test.skip(!process.env.AUTH_E2E, 'Requires real account mode')

test('field errors, advisory password strength, duplicate names and safe login errors', async ({
  page,
}) => {
  await page.goto('/#/')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.locator('#username-error')).toContainText('3–32')
  await expect(page.getByLabel('用户名', { exact: true })).toBeFocused()
  await expect(page.locator('#password-error')).toContainText('10–128')
  await page.getByLabel('用户名', { exact: true }).fill('   ')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.locator('#username-error')).toContainText('3–32')
  await page.getByRole('button', { name: '没有账号？创建账号' }).click()
  await page.getByLabel('密码', { exact: true }).fill('123')
  await expect(page.locator('#password-strength')).toContainText('长度不足')
  await page.getByLabel('密码', { exact: true }).fill('1234567890')
  await expect(page.locator('#password-strength')).toContainText('弱')
  const name = 'opt_' + Date.now()
  await page.getByLabel('用户名', { exact: true }).fill(name)
  await page.getByRole('button', { name: '注册并登录', exact: true }).click()
  await expect(page.getByRole('button', { name: '退出登录', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '退出登录', exact: true }).click()
  await page.getByRole('button', { name: '没有账号？创建账号' }).click()
  await page.getByLabel('用户名', { exact: true }).fill(name)
  await page.getByLabel('密码', { exact: true }).fill('Strong-password-123!')
  await expect(page.locator('#password-strength')).toContainText('强')
  await page.getByRole('button', { name: '注册并登录', exact: true }).click()
  await expect(page.locator('#username-error')).toContainText('用户名不可用')
  await page.getByRole('button', { name: '已有账号？去登录' }).click()
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('用户名或密码不正确')
  await page.getByLabel('用户名', { exact: true }).fill('missing_' + Date.now())
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('用户名或密码不正确')
  await page.getByLabel('用户名', { exact: true }).fill(name)
  await page.getByLabel('密码', { exact: true }).fill('1234567890')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('button', { name: '退出登录', exact: true })).toBeVisible()
})
