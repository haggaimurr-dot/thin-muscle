import {test,expect} from '@playwright/test'
test.skip(!!process.env.AUTH_E2E,'Demo market')
test('favorite work persists and creator only exposes public works',async({page})=>{
 await page.goto('/#/market')
 await page.locator('.product-card').first().click()
 let detail=page.getByRole('dialog').first()
 const title=await detail.locator('h2').first().innerText()
 await detail.getByRole('button',{name:'收藏作品',exact:true}).click()
 await expect(detail.getByRole('button',{name:'取消作品收藏'})).toBeVisible()
 await detail.getByRole('button',{name:'创作者主页'}).click()
 const creator=page.getByRole('dialog',{name:'创作者公开主页',exact:true})
 await expect(creator).toContainText('公开作品')
 await creator.getByRole('button',{name:'关闭',exact:true}).click()
 await detail.getByRole('button',{name:'关闭',exact:true}).click()
 await page.getByRole('button',{name:'收藏与推荐',exact:true}).click()
 await expect(page.getByRole('region',{name:'作品收藏与推荐'})).toContainText('按账号训练等级匹配')
 await expect(page.getByRole('button',{name:'查看收藏作品'}).first()).toBeVisible()
 await page.reload()
 await page.getByRole('button',{name:'收藏与推荐',exact:true}).click()
 await page.getByRole('button',{name:'查看收藏作品'}).first().click()
 await expect(page.getByRole('dialog').getByRole('button',{name:'取消作品收藏'})).toBeVisible()
})
