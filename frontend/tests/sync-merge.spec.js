import { test, expect } from '@playwright/test'
test.skip(!process.env.AUTH_E2E, 'Requires accounts')
test('two devices merge independent changes and choose same-field conflict explicitly', async ({ page, browser }) => {
  const username = 'merge_' + Date.now(), password = 'Merge-Password-123'
  await page.goto('/#/nutrition')
  await page.getByRole('button', { name: '没有账号？创建账号' }).click()
  await page.getByLabel('用户名', { exact: true }).fill(username)
  await page.getByLabel('密码', { exact: true }).fill(password)
  await page.getByRole('button', { name: '注册并登录', exact: true }).click()
  await page.getByRole('button', { name: '+10g', exact: true }).click()
  await expect(page.locator('.sync-banner')).toContainText('已同步到账号')
  const context = await browser.newContext({ baseURL: 'http://127.0.0.1:5174' })
  const other = await context.newPage()
  await other.goto('/#/')
  await other.getByLabel('用户名', { exact: true }).fill(username)
  await other.getByLabel('密码', { exact: true }).fill(password)
  await other.getByRole('button', { name: '登录', exact: true }).click()
  await other.getByLabel('力量训练目标天数').fill('8')
  await other.getByRole('button', { name: '保存本周期目标' }).click()
  await expect(other.locator('.sync-banner')).toContainText('已同步到账号')
  await page.getByRole('button', { name: '+25g', exact: true }).click()
  await expect(page.locator('.sync-banner')).toContainText('版本冲突')
  await page.getByRole('button', { name: '预览合并两端记录' }).click()
  const merge = page.getByRole('dialog', { name: '预览两端记录合并' })
  await expect(merge).toContainText('需要选择的冲突：0 项')
  await merge.getByRole('button', { name: '确认合并并同步' }).click()
  await expect(page.locator('.sync-banner')).toContainText('已同步到账号')
  await expect(page.locator('.protein-ring strong')).toHaveText('35')
  await page.goto('/#/')
  await expect(page.getByLabel('力量训练目标天数')).toHaveValue('8')
  await other.reload()
  await other.goto('/#/nutrition')
  await expect(other.locator('.protein-ring strong')).toHaveText('35')
  await other.getByLabel('每日蛋白目标（g）').fill('130')
  await other.getByRole('button', { name: '保存蛋白目标', exact: true }).click()
  await expect(other.locator('.sync-banner')).toContainText('已同步到账号')
  await page.goto('/#/nutrition')
  await page.getByLabel('每日蛋白目标（g）').fill('120')
  await page.getByRole('button', { name: '保存蛋白目标', exact: true }).click()
  await expect(page.locator('.sync-banner')).toContainText('版本冲突')
  await page.getByRole('button', { name: '预览合并两端记录' }).click()
  await expect(merge.getByRole('button', { name: '确认合并并同步' })).toBeDisabled()
  await merge.getByLabel('保留云端内容', { exact: true }).check()
  await merge.getByRole('button', { name: '确认合并并同步' }).click()
  await expect(page.locator('.protein-ring')).toContainText('/ 130 g')
  await page.reload()
  await expect(page.locator('.protein-ring')).toContainText('/ 130 g')
  await context.close()
})
