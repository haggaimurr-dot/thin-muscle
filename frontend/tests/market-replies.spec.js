import { test, expect } from '@playwright/test'
test.skip(!!process.env.AUTH_E2E, 'Demo market')
test('one-level replies can be reported and removed by their author', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/#/market')
  await page.locator('.product-card').first().click()
  const dialog = page.getByRole('dialog').first()
  await dialog.getByLabel('商品留言', { exact: true }).fill('回复流程父留言')
  await dialog.getByRole('button', { name: '发送', exact: true }).click()
  const row = dialog.locator('.comment-row').filter({ hasText: '回复流程父留言' })
  await row.getByLabel('商品留言回复').fill('这是一层回复')
  await row.getByRole('button', { name: '回复留言' }).click()
  await expect(row).toContainText('这是一层回复')
  await row.getByRole('button', { name: '举报回复' }).click()
  await page
    .getByRole('dialog', { name: '举报市场内容' })
    .getByLabel('举报原因')
    .fill('测试回复举报')
  await page.getByRole('button', { name: '提交举报' }).click()
  await expect(page.getByRole('dialog', { name: '举报市场内容' })).toContainText('举报已受理')
  await page.getByRole('button', { name: '完成', exact: true }).click()
  await row.getByRole('button', { name: '删除回复', exact: true }).click()
  await page.getByRole('button', { name: '确认删除回复' }).click()
  await expect(row).not.toContainText('这是一层回复')
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
  await row.getByRole('button', { name: '删除商品留言', exact: true }).click()
  await page.getByRole('button', { name: '取消删除留言' }).click()
  await expect(row).toBeVisible()
  await row.getByRole('button', { name: '删除商品留言', exact: true }).click()
  await page.getByRole('button', { name: '确认删除商品留言', exact: true }).click()
  await expect(row).toHaveCount(0)
})
